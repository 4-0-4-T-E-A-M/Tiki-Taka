                                         "schedule_id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                         "performance_id" bigint NOT NULL,
                                         "performance_datetime" timestamp NOT NULL,
                                         "open_at" timestamp NOT NULL, -- 예매 오픈 시각(#75). 공연 오픈 스케줄러가 이 시각 기준으로 OPEN 전환
