                         "seat_id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                         "section_id" bigint NOT NULL,
                         "row_name" varchar NOT NULL,
                         "seat_number" int NOT NULL,
                         "grade" seat_grade NOT NULL,
                         "price" int NOT NULL,
                         "status" seat_status NOT NULL,
                         "seat_score" int,
                         "priority_rank" int,
                         "version" bigint NOT NULL
);

CREATE TABLE "simulations" (
                               "simulation_id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                               "user_id" bigint NOT NULL,
                               "schedule_id" bigint NOT NULL,
                               "scheduled_start_time" timestamp NOT NULL,
                               "virtual_user_count" int NOT NULL,
